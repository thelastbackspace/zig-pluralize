test "basic pairs: plural, singular, and checks" {
    var p = try pl.Pluralize.init(t.allocator);
    defer p.deinit();

    for (pairs) |pair| {
        const got_plural = try p.plural(t.allocator, pair.single);
        defer t.allocator.free(got_plural);
        if (!std.mem.eql(u8, got_plural, pair.plural)) {
            std.debug.print("plural({s}) = {s}, want {s}\n", .{ pair.single, got_plural, pair.plural });
            return error.TestUnexpectedResult;
        }

        const got_single = try p.singular(t.allocator, pair.plural);
        defer t.allocator.free(got_single);
        if (!std.mem.eql(u8, got_single, pair.single)) {
            std.debug.print("singular({s}) = {s}, want {s}\n", .{ pair.plural, got_single, pair.single });
            return error.TestUnexpectedResult;
        }

        if (!p.isPlural(pair.plural)) {
            std.debug.print("isPlural({s}) = false\n", .{pair.plural});
            return error.TestUnexpectedResult;
        }
        if (!p.isSingular(pair.single)) {
            std.debug.print("isSingular({s}) = false\n", .{pair.single});
            return error.TestUnexpectedResult;
        }
    }
}

test "count picks singular or plural" {
    var p = try pl.Pluralize.init(t.allocator);
    defer p.deinit();

    for (pairs) |pair| {
        const as_count_1 = try p.count(t.allocator, pair.plural, 1, false);
        defer t.allocator.free(as_count_1);
