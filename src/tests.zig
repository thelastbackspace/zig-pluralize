test "custom rules" {
    var p = try pl.Pluralize.init(t.allocator);
    defer p.deinit();

    // Irregular.
    try p.addIrregularRule("canadia", "canadensis");
    {
        const got = try p.plural(t.allocator, "canadia");
        defer t.allocator.free(got);
        try t.expectEqualStrings("canadensis", got);
    }
    {
        const got = try p.singular(t.allocator, "canadensis");
        defer t.allocator.free(got);
        try t.expectEqualStrings("canadia", got);
    }

    // Uncountable.
    try p.addUncountableRule("paper");
    {
        const got = try p.plural(t.allocator, "paper");
        defer t.allocator.free(got);
        try t.expectEqualStrings("paper", got);
    }

    // Plural rule.
    try p.addPluralRule("gex$", "gexii");
    {
        const got = try p.plural(t.allocator, "regex");
        defer t.allocator.free(got);
        try t.expectEqualStrings("regexii", got);
    }

    // Singular rule.
    try p.addSingularRule("s$", "");
    {
        const got = try p.singular(t.allocator, "appleS");
        defer t.allocator.free(got);
        try t.expectEqualStrings("apple", got);
    }
}
